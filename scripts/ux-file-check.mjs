import assert from 'node:assert/strict'
import { join } from 'node:path'

/** Real UI journeys share the same file:// browser and error/network collection. */
export async function checkJourneys({ open, seed, click, text, stores, settle, scenarios, root }) {
  const { page, context } = await open({ withTextbook: true })
  const pk = '346-fusion-platform-v1'
  const setValue = async (selector, value) => {
    await page.$eval(selector, (input, next) => {
      Object.getOwnPropertyDescriptor(input.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype, 'value').set.call(input, next)
      input.dispatchEvent(new Event('input', { bubbles: true }))
    }, value)
  }
  const initial = await stores(page)
  await page.$eval('.coach-footer details', n => { n.open = true })
  await page.select('[aria-label="今日预算"]', '30')
  assert.equal((await stores(page)).platform.settings.minutes, initial.platform.settings.minutes)
  await click(page, '今天先到这里')
  assert.equal((await stores(page)).platform.day.closed, true)
  await page.reload({ waitUntil: 'networkidle0' })
  assert.ok((await text(page)).includes('今天已收工'))
  assert.equal(await page.$('main button[data-testid="start-training"]'), null)
  assert.ok(!(await text(page)).includes('回到今日'))
  await click(page, '恢复今日训练')
  assert.deepEqual((await stores(page)).platform.day.tasks, initial.platform.day.tasks)
  assert.equal((await stores(page)).platform.day.budgetMinutes, 30)
  assert.ok(await page.$('[data-testid="start-training"]'))
  scenarios.push('临时预算不修改每日默认值；收工刷新保持，可显式恢复且不重置预算或任务')

  await click(page, '设置数据', '.side')
  const beforePolicy = await stores(page)
  const chapters = beforePolicy.platform.day.selectedChapters
  const input = '[aria-label="运动生理学权重"]'
  await page.focus(input); await setValue(input, '')
  assert.deepEqual((await stores(page)).platform.settings, beforePolicy.platform.settings)
  await page.$eval(input, n => n.blur())
  assert.ok((await text(page)).includes('原设置未改动'))
  await page.focus(input); await setValue(input, '4')
  assert.equal((await stores(page)).platform.settings.subjects['运动生理学'].weight, 2)
  await page.keyboard.press('Enter')
  assert.equal((await stores(page)).platform.settings.subjects['运动生理学'].weight, 4)
  assert.deepEqual((await stores(page)).platform.day.selectedChapters, chapters)
  await page.focus(input); await setValue(input, '0'); await page.keyboard.press('Enter')
  assert.equal((await stores(page)).platform.settings.subjects['运动生理学'].weight, 4)
  await page.focus(input); await page.keyboard.press('Escape')
  assert.equal(await page.$eval(input, n => n.value), '4')
  await page.focus(input); await setValue(input, '4.5'); await page.keyboard.press('Enter')
  assert.equal((await stores(page)).platform.settings.subjects['运动生理学'].weight, 4.5)
  await page.select('[aria-label="每日默认预算"]', '90')
  const afterBudget = await stores(page)
  assert.equal(afterBudget.platform.day.budgetMinutes, 90)
  assert.equal(afterBudget.platform.settings.minutes, 90)
  scenarios.push('数字输入可清空编辑，非法值不保存，Enter 提交、Esc 撤回；调整权重不重新选章节，每日预算作用明确')

  // Imported valid budgets need an actual matching option instead of a blank select.
  const custom = await stores(page)
  custom.platform.day.budgetMinutes = 240; custom.platform.settings.minutes = 240
  await seed(page, custom.platform, custom.mrc)
  await page.$eval('.coach-footer details', n => { n.open = true })
  assert.equal(await page.$eval('[aria-label="今日预算"]', n => n.value), '240')
  for (const policy of Object.values(custom.platform.settings.subjects)) policy.newCap = 0
  await seed(page, custom.platform, custom.mrc)
  assert.ok((await text(page)).includes('当前新学配额或章节范围'))
  assert.ok(!(await text(page)).includes('今日安排已完成'))
  await click(page, '查看训练安排')
  assert.ok((await text(page)).includes('全科安排'))
  scenarios.push('导入的240分钟预算正确显示；暂停新学时不误报全部完成，并提供设置入口')

  await click(page, '资料库', '.side')
  await page.type('[aria-label="查找资料"]', '不存在的查询词ZZZ')
  assert.ok((await text(page)).includes('没有找到匹配的资料'))
  assert.ok(!(await text(page)).includes('请在旧程序导出'))
  await click(page, '清除筛选')
  await settle(page, () => document.querySelectorAll('ul.plain > li').length === 60)
  assert.equal(await page.$$('ul.plain > li').then(n => n.length), 60)
  await click(page, '录入教材条目')
  await setValue('form input[required]', 'UX草稿保留测试')
  await setValue('form textarea[required]', '用户输入的正文与机制。')
  await click(page, '体育概论')
  assert.ok((await text(page)).includes('录入到 运动生理学'))
  await click(page, '今日训练', '.side'); await click(page, '资料库', '.side')
  assert.equal(await page.$eval('form input[required]', n => n.value), 'UX草稿保留测试')
  assert.equal(await page.$eval('form textarea[required]', n => n.value), '用户输入的正文与机制。')
  await click(page, '保存条目')
  const newPoint = (await stores(page)).platform.general.points.find(p => p.title === 'UX草稿保留测试')
  assert.equal(newPoint.subject, '运动生理学')
  assert.ok((await text(page)).includes('条目已保存'))
  await click(page, 'UX草稿保留测试')
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), '资料详情')
  await click(page, '收起')
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'UX草稿保留测试')
  scenarios.push('搜索无结果可清除筛选；录入草稿跨页面保留，切换查询科目不误存，详情打开和收起正确交接焦点')

  await click(page, '管理学资料')
  assert.ok((await text(page)).includes('返回全科资料库'))
  await click(page, '返回全科资料库')
  await click(page, '学习记录', '.side'); await click(page, '查看管理学记录')
  assert.ok((await text(page)).includes('返回学习记录'))
  await click(page, '返回学习记录'); await click(page, '查看今日推荐')
  assert.equal(await page.evaluate(() => document.activeElement?.id), 'study-main')
  assert.ok((await page.title()).includes('今日作战台'))
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
  await click(page, '设置数据', '.side')
  assert.equal(await page.evaluate(() => window.scrollY), 0)
  scenarios.push('管理学子页面返回对应全科入口，页面切换更新焦点、标题并回到顶部')

  // Recovery is destructive: request/cancel must preserve all current records.
  const preRestore = await stores(page)
  await page.evaluate((p, m) => localStorage.setItem('346-fusion-backup-v1', JSON.stringify({ '346-fusion-platform-v1': JSON.stringify(p), 'pku346-recall-v1': JSON.stringify(m) })), initial.platform, initial.mrc)
  await page.$eval('details', n => { n.open = true })
  await click(page, '恢复整包导入前备份')
  await settle(page, () => Boolean(document.querySelector('dialog[open]')))
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), '取消恢复')
  assert.deepEqual(await stores(page), preRestore)
  await page.keyboard.press('Escape')
  assert.deepEqual(await stores(page), preRestore)
  await click(page, '恢复整包导入前备份')
  await click(page, '确认恢复旧备份', 'dialog')
  assert.equal((await stores(page)).platform.general.points.some(p => p.id === newPoint.id), false)
  scenarios.push('恢复旧备份先确认，默认焦点在取消；Esc 不改数据，明确确认才替换两模块')

  await click(page, '设置数据', '.side'); await click(page, '管理学闭卷考试')
  await page.focus('input[type="number"]'); await setValue('input[type="number"]', '')
  assert.equal(await page.$$eval('button', nodes => nodes.find(n => n.textContent === 'A 题限时写作').disabled), true)
  await setValue('input[type="number"]', '15'); await click(page, 'A 题限时写作')
  await page.type('textarea', '这份考试作答必须保留。')
  const examBefore = (await stores(page)).mrc.exam
  await click(page, '结束')
  assert.deepEqual((await stores(page)).mrc.exam, examBefore)
  await click(page, '继续考试')
  assert.deepEqual((await stores(page)).mrc.exam, examBefore)
  await click(page, '结束'); await click(page, '确认结束并清除')
  assert.equal((await stores(page)).mrc.exam, null)
  scenarios.push('考试空时长不能启动限时写作；结束前提示导出，取消保留作答，确认才清除')

  await page.setViewport({ width: 320, height: 740 })
  for (const label of ['今日训练', '资料库', '学习记录', '设置数据']) {
    await click(page, label, '.mobile-nav')
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `320px overflow: ${label}`)
  }
  await page.screenshot({ path: join(root, 'reports/ux-settings-mobile.png'), fullPage: true })
  for (const label of ['管理学详细设置', '训练方法', '管理学闭卷考试']) {
    await click(page, label)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `320px overflow: ${label}`)
    await click(page, '设置数据', '.mobile-nav')
  }
  await click(page, '资料库', '.mobile-nav'); await click(page, '管理学资料')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '320px overflow: MRC library')
  await click(page, '学习记录', '.mobile-nav')
  for (const label of ['查看管理学记录', '查看管理学错漏']) {
    await click(page, label)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `320px overflow: ${label}`)
    await click(page, '学习记录', '.mobile-nav')
  }
  await page.setViewport({ width: 1280, height: 900 })
  await click(page, '资料库', '.side')
  await page.screenshot({ path: join(root, 'reports/ux-library-desktop.png'), fullPage: true })
  scenarios.push('320px 四个主页面及管理学资料、档案、错漏、方法、设置、考试均无横向溢出')
  await context.close()
}
